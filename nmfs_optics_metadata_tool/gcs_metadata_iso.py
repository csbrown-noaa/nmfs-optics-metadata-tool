def inspect_site_folder(bucket, site_prefix):
    blobs = list(bucket.list_blobs(prefix=site_prefix))
    total_size_bytes = sum(b.size for b in blobs if b.size)
    file_count = len([b for b in blobs if not b.name.endswith('/')])
    file_extensions = sorted(list({b.name.split('.')[-1] for b in blobs if '.' in b.name}))
    last_modified = max((b.updated for b in blobs if b.updated), default=None)

    return {
        "file_count": file_count,
        "total_size_mb": round(total_size_bytes / (1024 * 1024), 2),
        "formats": ", ".join(file_extensions),
        "last_updated": last_modified.isoformat() if last_modified else None
    }

