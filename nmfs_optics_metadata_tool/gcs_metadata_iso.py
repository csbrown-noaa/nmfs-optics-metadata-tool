# ================= CONFIGURATION =================
BUCKET_NAME = "nmfs-dev-uc1-sefsc"
SURVEY_PREFIX = "GFISHER/Video_data/2025"  # Keep empty "" if sites sit at root
COLLECTOR_SPREADSHEET = "2025_GCSbucket_metadata.csv"
PARENT_TITLE = "Regional Environmental Survey Collection"
PARENT_ABSTRACT = (
    "Comprehensive field survey campaign across multiple designated monitoring "
    "sites, including drone photogrammetry, sensor readings, and quadrat logs."
)
# =================================================

NSMAP = {
    "gmd": "http://www.isotc211.org/2005/gmd",
    "gco": "http://www.isotc211.org/2005/gco",
    "gts": "http://www.isotc211.org/2005/gts",
    "gml": "http://www.opengis.net/gml/3.2",
    "xsi": "http://www.w3.org/2001/XMLSchema-instance",
}

def sub_element(parent, tag, text=None):
    el = etree.SubElement(parent, f"{{{NSMAP['gmd']}}}{tag}")
    if text is not None:
        gco_str = etree.SubElement(el, f"{{{NSMAP['gco']}}}CharacterString")
        gco_str.text = str(text)
    return el


def build_parent_iso19115_xml(master_df):
    """Builds a single ISO 19115 / 19139 XML describing the collection."""
    root = etree.Element(f"{{{NSMAP['gmd']}}}MD_Metadata", nsmap=NSMAP)

    # 1. Identifier & Standard Specs
    sub_element(root, "fileIdentifier", str(uuid.uuid4()))
    lang = sub_element(root, "language")
    etree.SubElement(lang, f"{{{NSMAP['gco']}}}CharacterString").text = "eng"
    sub_element(root, "characterSet")

    # 2. Metadata Contact
    primary_owner = master_df["data_owner"].dropna().iloc[0] if "data_owner" in master_df and not master_df["data_owner"].dropna().empty else "Lead Investigator"
    primary_org = master_df["owner_org"].dropna().iloc[0] if "owner_org" in master_df and not master_df["owner_org"].dropna().empty else "Survey Operations Group"
    primary_email = master_df["owner_email"].dropna().iloc[0] if "owner_email" in master_df and not master_df["owner_email"].dropna().empty else "admin@example.org"

    md_contact = sub_element(root, "contact")
    rp = sub_element(md_contact, "CI_ResponsibleParty")
    sub_element(rp, "individualName", primary_owner)
    sub_element(rp, "organisationName", primary_org)
    addr_info = sub_element(sub_element(rp, "contactInfo"), "CI_Contact")
    ci_addr = sub_element(sub_element(addr_info, "address"), "CI_Address")
    sub_element(ci_addr, "electronicMailAddress", primary_email)
    role = sub_element(rp, "role")
    etree.SubElement(
        role,
        f"{{{NSMAP['gmd']}}}CI_RoleCode",
        codeList="http://standards.iso.org/iso/19139/resources/gmxCodelists.xml#CI_RoleCode",
        codeListValue="custodian",
    ).text = "custodian"

    date_el = sub_element(root, "dateStamp")
    dt = etree.SubElement(date_el, f"{{{NSMAP['gco']}}}DateTime")
    dt.text = datetime.now(timezone.utc).isoformat()

    sub_element(root, "metadataStandardName", "ISO 19115-1:2014 / ISO 19139")
    sub_element(root, "metadataStandardVersion", "1.0")

    hierarchy = sub_element(root, "hierarchyLevel")
    etree.SubElement(
        hierarchy,
        f"{{{NSMAP['gmd']}}}MD_ScopeCode",
        codeList="http://standards.iso.org/iso/19139/resources/gmxCodelists.xml#MD_ScopeCode",
        codeListValue="series",
    ).text = "series"

    # 3. Data Identification
    id_info = sub_element(root, "identificationInfo")
    data_ident = sub_element(id_info, "MD_DataIdentification")

    citation = sub_element(data_ident, "citation")
    ci_citation = sub_element(citation, "CI_Citation")
    sub_element(ci_citation, "title", PARENT_TITLE)
    c_date = sub_element(ci_citation, "date")
    ci_date = sub_element(c_date, "CI_Date")
    d_val = sub_element(ci_date, "date")
    etree.SubElement(d_val, f"{{{NSMAP['gco']}}}Date").text = datetime.now().strftime("%Y-%m-%d")
    d_type = sub_element(ci_date, "dateType")
    etree.SubElement(
        d_type,
        f"{{{NSMAP['gmd']}}}CI_DateTypeCode",
        codeList="http://standards.iso.org/iso/19139/resources/gmxCodelists.xml#CI_DateTypeCode",
        codeListValue="publication",
    ).text = "publication"

    sub_element(data_ident, "abstract", PARENT_ABSTRACT)

    topic = sub_element(data_ident, "topicCategory")
    etree.SubElement(topic, f"{{{NSMAP['gmd']}}}MD_TopicCategoryCode").text = "environment"

    # 4. Aggregated Sub-Dataset Entries (Site Subfolders)
    for _, row in master_df.iterrows():
        agg_info = sub_element(data_ident, "aggregationInfo")
        md_agg = sub_element(agg_info, "MD_AggregateInformation")
        agg_cit = sub_element(md_agg, "aggregateDataSetName")
        ci_agg_cit = sub_element(agg_cit, "CI_Citation")
        sub_element(ci_agg_cit, "title", str(row.get("title", f"Site: {row['site_id']}")))

        agg_ident = sub_element(ci_agg_cit, "identifier")
        md_ident = sub_element(agg_ident, "MD_Identifier")
        sub_element(md_ident, "code", str(row["site_id"]))

        assoc_type = sub_element(md_agg, "associationType")
        etree.SubElement(
            assoc_type,
            f"{{{NSMAP['gmd']}}}DS_AssociationTypeCode",
            codeList="http://standards.iso.org/iso/19139/resources/gmxCodelists.xml#DS_AssociationTypeCode",
            codeListValue="partOfSeamlessDatabase",
        ).text = "partOfSeamlessDatabase"

        init_type = sub_element(md_agg, "initiativeType")
        etree.SubElement(
            init_type,
            f"{{{NSMAP['gmd']}}}DS_InitiativeTypeCode",
            codeList="http://standards.iso.org/iso/19139/resources/gmxCodelists.xml#DS_InitiativeTypeCode",
            codeListValue="collection",
        ).text = "collection"

    # 5. Composite Geographic Extents
    extent = sub_element(data_ident, "extent")
    ex_extent = sub_element(extent, "EX_Extent")
    geo_el = sub_element(ex_extent, "geographicElement")
    bbox = sub_element(geo_el, "EX_GeographicBoundingBox")

    min_lon = master_df["west_bound_lon"].min() if "west_bound_lon" in master_df else -180.0
    max_lon = master_df["east_bound_lon"].max() if "east_bound_lon" in master_df else 180.0
    min_lat = master_df["south_bound_lat"].min() if "south_bound_lat" in master_df else -90.0
    max_lat = master_df["north_bound_lat"].max() if "north_bound_lat" in master_df else 90.0

    for tag, val, default in [
        ("westBoundLongitude", min_lon, -180.0),
        ("eastBoundLongitude", max_lon, 180.0),
        ("southBoundLatitude", min_lat, -90.0),
        ("northBoundLatitude", max_lat, 90.0),
    ]:
        b_sub = sub_element(bbox, tag)
        coord = val if pd.notna(val) else default
        etree.SubElement(b_sub, f"{{{NSMAP['gco']}}}Decimal").text = str(coord)

    # 6. Distribution Size
    dist_info = sub_element(root, "distributionInfo")
    md_dist = sub_element(dist_info, "MD_Distribution")
    transfer = sub_element(md_dist, "transferOptions")
    dig_transfer = sub_element(transfer, "MD_DigitalTransferOptions")
    size_el = sub_element(dig_transfer, "transferSize")
    total_size = round(master_df["total_size_mb"].sum(), 2)
    etree.SubElement(size_el, f"{{{NSMAP['gco']}}}Real").text = str(total_size)

    return etree.tostring(root, pretty_print=True, xml_declaration=True, encoding="UTF-8").decode("utf-8")


def get_outside_path(prefix, filename):
    """
    Computes the GCS object name outside of the target folder.
    - If prefix is 'survey_data/', outside path is 'survey_data_metadata.xml' (or placed at root '').
    - If prefix is 'projects/surveys/', outside path is 'projects/surveys_metadata.xml'.
    """
    clean_prefix = prefix.strip("/")
    if not clean_prefix:
        # Parent is already the bucket root
        return filename

    parts = clean_prefix.split("/")
    parent_dir_name = parts[-1]
    enclosing_dir = "/".join(parts[:-1])

    # Place alongside the folder in the enclosing directory
    prefix_base = f"{enclosing_dir}/" if enclosing_dir else ""
    return f"{prefix_base}{parent_dir_name}_{filename}"


def run_pipeline():
    client = storage.Client()
    bucket = client.bucket(BUCKET_NAME)
    prefix = SURVEY_PREFIX.strip("/") + "/" if SURVEY_PREFIX else ""

    # 1. Load external collector spreadsheet
    collector_df = (
        pd.read_excel(COLLECTOR_SPREADSHEET)
        if COLLECTOR_SPREADSHEET.endswith(".xlsx")
        else pd.read_csv(COLLECTOR_SPREADSHEET)
    )
    collector_df["site_id"] = collector_df["site_id"].astype(str).str.strip()

    # 2. Discover immediate subfolders (sites) only
    iterator = client.list_blobs(bucket, prefix=prefix, delimiter="/")
    list(iterator)
    site_folder_names = [p[len(prefix):].strip("/") for p in iterator.prefixes if p[len(prefix):].strip("/")]

    site_records = []
    print(f"Scanning {len(site_folder_names)} site directories under gs://{BUCKET_NAME}/{prefix}...")

    for site in site_folder_names:
        site_prefix = f"{prefix}{site}/"
        blobs = list(bucket.list_blobs(prefix=site_prefix))
        file_blobs = [b for b in blobs if not b.name.endswith("/")]

        total_bytes = sum(b.size for b in file_blobs if b.size)
        types = sorted(list({b.name.split(".")[-1] for b in file_blobs if "." in b.name}))
        last_mod = max((b.updated for b in file_blobs if b.updated), default=None)

        site_records.append({
            "site_id": site,
            "gcs_path": f"gs://{BUCKET_NAME}/{site_prefix}",
            "file_count": len(file_blobs),
            "total_size_mb": round(total_bytes / (1024 * 1024), 2),
            "file_types": ", ".join(types),
            "last_updated": last_mod.isoformat() if last_mod else None,
        })

    master_df = pd.merge(pd.DataFrame(site_records), collector_df, on="site_id", how="left")

    # 3. Target Path: Place the XML just outside the parent folder
    xml_object_name = get_outside_path(prefix, "iso19115_metadata.xml")

    print(f"Writing ISO 19115 XML outside parent folder to: gs://{BUCKET_NAME}/{xml_object_name}")
    parent_xml = build_parent_iso19115_xml(master_df)
    xml_blob = bucket.blob(xml_object_name)
    xml_blob.upload_from_string(parent_xml, content_type="application/xml")

    # 4. Write Quick-Look Summary Files (inside parent folder for browsing)
    readme_blob = bucket.blob(f"{prefix}README.md")
    readme_blob.upload_from_string(
        f"# Survey Data Directory\n\nTotal Sites: {len(master_df)}\nISO 19115 Manifest: `gs://{BUCKET_NAME}/{xml_object_name}`\n",
        content_type="text/markdown"
    )

    catalog_csv_blob = bucket.blob(f"{prefix}master_catalog.csv")
    catalog_csv_blob.upload_from_string(master_df.to_csv(index=False), content_type="text/csv")

    print("\nComplete! Object structure:")
    print(f"  [OUTSIDE XML]: gs://{BUCKET_NAME}/{xml_object_name}")
    print(f"  [PARENT DIR] : gs://{BUCKET_NAME}/{prefix}")
    print(f"  [README]     : gs://{BUCKET_NAME}/{prefix}README.md")
    print(f"  [CSV CATALOG]: gs://{BUCKET_NAME}/{prefix}master_catalog.csv")


if __name__ == "__main__":
    run_pipeline()
